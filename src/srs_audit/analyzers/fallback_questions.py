ORDER = {"Blocker": 0, "Critical": 1, "Major": 2, "Minor": 3}


def fallback_questions(defects: list[AuditDefect]) -> list[Question]:
    groups: dict[str, list[AuditDefect]] = {}
    for d in defects:
        if d.rule_id in T:
            groups.setdefault(d.rule_id, []).append(d)
    out: list[Question] = []
    for rule, ds in groups.items():
        t = T[rule]
        ds.sort(key=lambda d: ORDER[d.severity])
        out.append(
            Question(
                target_role=t["role"],
                question=t["q"],
                related_defect_ids=[d.defect_id for d in ds],
                options=t["options"],
                recommended_option=t["rec"],
                decision_impact=t["impact"],
                before_text=ds[0].exact_quote,
                after_ears_proposal=t["ears"],
                before_grounded=True,
                before_location=ds[0].verified_location,
            )
        )
    return out
